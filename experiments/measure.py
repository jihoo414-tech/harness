"""Summarize Claude Code sessions run inside an experiment folder into metrics.md.

Usage: python experiments/measure.py experiments/01-baseline [--junit DIR]
"""
import argparse
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path

PROJECTS = Path.home() / ".claude" / "projects"
HARNESS = Path(__file__).resolve().parent.parent
DENY = "The user doesn't want to proceed with this tool use"
INTERRUPT = "[Request interrupted by user"


def project_dir(exp: Path) -> Path:
    # Claude Code names the folder after the cwd with every non-alphanumeric char replaced by '-'
    return PROJECTS / re.sub(r"[^A-Za-z0-9]", "-", str(exp))


def texts(content):
    if isinstance(content, str):
        return [content]
    out = []
    for block in content or []:
        c = block.get("text") if block.get("type") == "text" else block.get("content")
        if isinstance(c, str):
            out.append(c)
        elif isinstance(c, list):
            out += [x.get("text", "") for x in c if isinstance(x, dict)]
    return out


def summarize(lines):
    s = dict(start=None, end=None, messages=0, denials=0, interrupts=0,
             input_tokens=0, output_tokens=0, models=set())
    seen = set()
    for line in lines:
        try:
            d = json.loads(line)
        except json.JSONDecodeError:
            continue
        if d.get("isSidechain"):
            continue
        ts = d.get("timestamp")
        if ts and d.get("type") in ("user", "assistant"):
            s["start"] = s["start"] or ts
            s["end"] = ts
        msg = d.get("message") or {}
        if d.get("type") == "user":
            body = texts(msg.get("content"))
            if any(t.startswith(INTERRUPT) for t in body):
                s["interrupts"] += 1
            elif any(t.startswith(DENY) for t in body):
                s["denials"] += 1
            elif (d.get("origin") or {}).get("kind") == "human" and not d.get("isMeta"):
                s["messages"] += 1
        elif d.get("type") == "assistant" and msg.get("id") not in seen:
            seen.add(msg.get("id"))  # one API response is split across several lines
            u = msg.get("usage") or {}
            s["input_tokens"] += sum(u.get(k, 0) for k in
                                     ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens"))
            s["output_tokens"] += u.get("output_tokens", 0)
            if msg.get("model") and not msg["model"].startswith("<"):
                s["models"].add(msg["model"])
    s["interventions"] = s["messages"] + s["denials"] + s["interrupts"]
    if s["start"]:
        span = datetime.fromisoformat(s["end"].replace("Z", "+00:00")) - \
               datetime.fromisoformat(s["start"].replace("Z", "+00:00"))
        s["minutes"] = round(span.total_seconds() / 60, 1)
    else:
        s["minutes"] = 0
    return s


def junit(dir_: Path):
    total = failed = 0
    for f in dir_.glob("*.xml"):
        r = ET.parse(f).getroot()
        total += int(r.get("tests", 0)) - int(r.get("skipped", 0))
        failed += int(r.get("failures", 0)) + int(r.get("errors", 0))
    return total - failed, total


def git_head():
    r = subprocess.run(["git", "-C", str(HARNESS), "log", "-1", "--format=%h %s"],
                       capture_output=True, text=True, encoding="utf-8")
    dirty = subprocess.run(["git", "-C", str(HARNESS), "status", "--porcelain"],
                           capture_output=True, text=True, encoding="utf-8").stdout.strip()
    return r.stdout.strip() + (" (+ uncommitted changes)" if dirty else "")


def skill_overrides():
    f = HARNESS / ".claude" / "settings.local.json"
    if not f.exists():
        return {}
    return json.loads(f.read_text(encoding="utf-8")).get("skillOverrides", {})


def render(exp, sessions, accept):
    rows = ["| session | minutes | my msgs | denials | interrupts | interventions | input tok | output tok | model |",
            "|---|---|---|---|---|---|---|---|---|"]
    for sid, s in sessions:
        rows.append(f"| {sid[:8]} | {s['minutes']} | {s['messages']} | {s['denials']} | {s['interrupts']} | "
                    f"{s['interventions']} | {s['input_tokens']:,} | {s['output_tokens']:,} | "
                    f"{', '.join(sorted(s['models']))} |")
    off = sorted(k for k, v in skill_overrides().items() if v == "off")
    name_only = sorted(k for k, v in skill_overrides().items() if v == "name-only")
    out = [f"# Metrics: {exp.name}", "", "Generated by `experiments/measure.py`. Do not edit by hand.", "",
           *rows, ""]
    if accept:
        passed, total = accept
        pct = f"{passed / total:.0%}" if total else "n/a"
        out += [f"Acceptance tests: {passed}/{total} passed ({pct})", ""]
    out += ["## Fixed conditions", "",
            f"- Harness commit: {git_head()}",
            f"- Skills off: {', '.join(off) or 'none'}",
            f"- Skills name-only: {', '.join(name_only) or 'none'}", ""]
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("experiment", type=Path)
    p.add_argument("--junit", type=Path, help="JUnit XML dir from the hidden acceptance tests")
    a = p.parse_args()
    exp = a.experiment.resolve()
    pdir = project_dir(exp)
    files = sorted(pdir.glob("*.jsonl"), key=lambda f: f.stat().st_mtime)
    if not files:
        sys.exit(f"No sessions found in {pdir}. Run claude from inside {exp} first.")
    sessions = [(f.stem, summarize(f.open(encoding="utf-8", errors="replace"))) for f in files]
    accept = junit(a.junit) if a.junit else None
    (exp / "metrics.md").write_text(render(exp, sessions, accept), encoding="utf-8")
    print(f"Wrote {exp / 'metrics.md'} ({len(sessions)} session(s))")


if __name__ == "__main__":
    main()
